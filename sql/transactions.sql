-- =====================================================================
-- TaskFlow transaction examples (PostgreSQL)
--
-- Run after `python manage.py seed_demo`, from the project root:
--   docker exec -i taskflow-db psql -U taskflow -d taskflow < sql/transactions.sql
-- or, with a local psql client:
--   psql -U taskflow -d taskflow -f sql/transactions.sql
--
-- psql keeps going after an error by default (ON_ERROR_STOP is off),
-- which is what lets Example 2 show the failure and then the ROLLBACK.
-- The script cleans up its own rows first, so it can be re-run.
-- =====================================================================

\echo '--- cleanup from previous runs ---'
DELETE FROM project
WHERE owner_id = (SELECT id FROM auth_user WHERE username = 'demo')
  AND name IN ('Txn demo: committed', 'Txn demo: rolled back');


-- ---------------------------------------------------------------------
-- Example 1: COMMIT
-- A project, its milestones and a first task are created as one unit.
-- All four INSERTs become visible together when COMMIT succeeds.
-- ---------------------------------------------------------------------
\echo ''
\echo '=== Example 1: COMMIT ==='
BEGIN;

INSERT INTO project (owner_id, name, description, start_date, deadline, status)
VALUES ((SELECT id FROM auth_user WHERE username = 'demo'),
        'Txn demo: committed', 'Created inside one transaction',
        CURRENT_DATE, CURRENT_DATE + 30, 'ACTIVE');

-- currval() returns the project_id generated by the INSERT above
-- in this session, so the children point at the new project.
INSERT INTO milestone (project_id, name, deadline)
VALUES (currval(pg_get_serial_sequence('project', 'project_id')), 'Design', CURRENT_DATE + 10),
       (currval(pg_get_serial_sequence('project', 'project_id')), 'Build',  CURRENT_DATE + 25);

INSERT INTO task (project_id, title, priority)
VALUES (currval(pg_get_serial_sequence('project', 'project_id')), 'Kick-off meeting', 'HIGH');

COMMIT;

\echo 'After COMMIT the project, both milestones and the task exist:'
SELECT p.name AS project,
       (SELECT COUNT(*) FROM milestone m WHERE m.project_id = p.project_id) AS milestones,
       (SELECT COUNT(*) FROM task t      WHERE t.project_id = p.project_id) AS tasks
FROM project p
WHERE p.name = 'Txn demo: committed';


-- ---------------------------------------------------------------------
-- Example 2: ROLLBACK
-- Same shape, but the task INSERT violates CHECK ck_task_priority
-- ('URGENT' is not LOW/MEDIUM/HIGH). PostgreSQL marks the transaction
-- as aborted, every later statement is refused, and ROLLBACK undoes the
-- project and milestones that had already been inserted.
-- ---------------------------------------------------------------------
\echo ''
\echo '=== Example 2: ROLLBACK ==='
BEGIN;

INSERT INTO project (owner_id, name, description, start_date, deadline, status)
VALUES ((SELECT id FROM auth_user WHERE username = 'demo'),
        'Txn demo: rolled back', 'This row must not survive',
        CURRENT_DATE, CURRENT_DATE + 30, 'PLANNED');

INSERT INTO milestone (project_id, name)
VALUES (currval(pg_get_serial_sequence('project', 'project_id')), 'Txn phase 1'),
       (currval(pg_get_serial_sequence('project', 'project_id')), 'Txn phase 2');

\echo 'Inside the transaction the project is visible to this session:'
SELECT name, status FROM project WHERE name = 'Txn demo: rolled back';

\echo 'Now the failing INSERT (expect: violates check constraint "ck_task_priority"):'
INSERT INTO task (project_id, title, priority)
VALUES (currval(pg_get_serial_sequence('project', 'project_id')), 'Bad task', 'URGENT');

\echo 'Any further statement is rejected (expect: current transaction is aborted):'
SELECT 1;

ROLLBACK;

\echo 'After ROLLBACK nothing from Example 2 remains (expect 0 rows / 0 milestones):'
SELECT COUNT(*) AS projects_left
FROM project WHERE name = 'Txn demo: rolled back';

SELECT COUNT(*) AS milestones_left
FROM milestone WHERE name IN ('Txn phase 1', 'Txn phase 2');
